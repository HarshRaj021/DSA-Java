package ch2_Pattern;

public class Pattern2 {
   
    public static void main(String[] args) {
        int n = 5;
        int k = 3;
        for(int i = 1; i<=k;i++){
            for(int j = 1; j<=n;j++){
                System.out.print("*");
            }
            System.out.println();
        }
    }
    
}

    

